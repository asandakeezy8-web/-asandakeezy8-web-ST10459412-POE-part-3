package com.mycompany.main;

import org.junit.Before;
import org.junit.Test;

import java.util.List;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertTrue;

public class MessageTest {

    private static final String NUM1 = "+27718693002";
    private static final String MSG1 = "Hi Mike, can you join us for dinner tonight?";
    private static final String NUM2 = "08575975889";
    private static final String MSG2 = "Hi Keegan, did you receive the payment?";

    @Before
    public void setUp() {
        Message.resetState();
    }

    // ---- Message length (success and failure) ----
    @Test
    public void messageLengthSuccess() {
        assertEquals("Message ready to send.", new Message("0012345678", NUM1, MSG1).checkMessageLength());
    }

    @Test
    public void messageLengthFailure() {
        String tooLong = "a".repeat(260);
        assertEquals("Message exceeds 250 characters by 10, please reduce the size.",
                new Message("0012345678", NUM1, tooLong).checkMessageLength());
    }

    // ---- Recipient number (success and failure) ----
    @Test
    public void recipientSuccess() {
        assertEquals("Cell phone number successfully captured.",
                new Message("0012345678", NUM1, MSG1).checkRecipientCell());
    }

    @Test
    public void recipientFailure() {
        assertEquals("Cell phone number is incorrectly formatted or does not contain an international code. "
                        + "Please correct the number and try again.",
                new Message("0012345678", NUM2, MSG2).checkRecipientCell());
    }

    // ---- Message hash ----
    @Test
    public void messageHashTestCase1() {
        assertEquals("00:0:HITONIGHT", new Message("0012345678", NUM1, MSG1).createMessageHash());
    }

    /** Remainder of the hashes checked in a loop over the sent messages. */
    @Test
    public void messageHashesInLoop() {
        String[] numbers = {NUM1, NUM1};
        String[] texts = {MSG1, "Hi Keegan, did you receive the payment?"};
        String[] expectedWords = {"HITONIGHT", "HIPAYMENT"};

        for (int i = 0; i < texts.length; i++) {
            new Message(numbers[i], texts[i]).SentMessage(1);
        }
        List<Message> sent = Message.getSentMessages();
        assertEquals(2, sent.size());
        for (int i = 0; i < sent.size(); i++) {
            Message m = sent.get(i);
            String expected = m.getMessageID().substring(0, 2) + ":" + i + ":" + expectedWords[i];
            assertEquals(expected, m.getMessageHash());
        }
    }

    // ---- Message ID ----
    @Test
    public void messageIdCreated() {
        Message m = new Message("0012345678", NUM1, MSG1);
        assertEquals("Message ID generated: 0012345678", m.generateMessageID());
        assertTrue(m.checkMessageID());
    }

    @Test
    public void autoGeneratedIdIsTenDigits() {
        Message m = new Message(NUM1, MSG1);
        assertEquals(10, m.getMessageID().length());
        assertTrue(m.checkMessageID());
    }

    // ---- MessageSent (Send / Disregard / Store) ----
    @Test
    public void sentMessageSend() {
        assertEquals("Message successfully sent.", new Message("0012345678", NUM1, MSG1).SentMessage(1));
    }

    @Test
    public void sentMessageDisregard() {
        assertEquals("Press 0 to delete the message.", new Message("0087654321", NUM2, MSG2).SentMessage(2));
    }

    @Test
    public void sentMessageStore() {
        assertEquals("Message successfully stored.", new Message("0012345678", NUM1, MSG1).SentMessage(3));
    }

    // ---- Task test data: message 1 sent, message 2 discarded ----
    @Test
    public void totalAfterSendAndDiscard() {
        Message one = new Message(NUM1, MSG1);
        Message two = new Message(NUM2, MSG2);
        assertEquals("Message successfully sent.", one.SentMessage(1));
        assertEquals("Press 0 to delete the message.", two.SentMessage(2));
        assertEquals(1, one.returnTotalMessagess());
        assertTrue(one.printMessages().contains("Message ID: " + one.getMessageID()));
        assertTrue(one.printMessages().contains("Message Hash: " + one.getMessageHash()));
    }
}
